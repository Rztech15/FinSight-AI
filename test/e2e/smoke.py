        pg.click("[data-action=auth-mode][data-mode=reset]"); pg.wait_for_selector("text=Reset your password"); pg.screenshot(path=f"{SHOTS}/reset-password.png")
        pg.click("text=Continue as guest"); pg.wait_for_selector(".hm-hero")
