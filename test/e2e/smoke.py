        check("home page has no sidebar", not pg.locator(".sidebar").is_visible())
        check("home preview shows dashes (no made-up numbers) before any data", pg.locator(".hm-kpis").inner_text().count("—") == 3 and "$" not in pg.locator(".hm-kpis").inner_text() and "46" not in pg.locator(".hm-dev-ring").inner_text())
        pg.screenshot(path=f"{SHOTS}/home.png", full_page=True)
        pg.goto(f"{BASE}/#/dashboard"); pg.wait_for_selector(".welcome")
        pg.screenshot(path=f"{SHOTS}/welcome.png", full_page=True)
        pg.goto(f"{BASE}/#/home"); pg.wait_for_selector(".hm-hero")
        pg.click(".hm-cta a.solid"); pg.wait_for_selector("[data-dropzone]")
        check("home 'Upload Your Data' goes to upload", True)
        pg.goto(f"{BASE}/#/home"); pg.wait_for_selector(".hm-hero")
        pg.click(".hm-cta button.ghost"); pg.wait_for_selector(".kpi")
        check("home 'Explore Demo' loads the demo dashboard", pg.locator(".kpi").count() == 6)
        pg.goto(f"{BASE}/#/dashboard")
        rc = b.new_context(color_scheme="dark"); rp = rc.new_page(); rp.add_init_script("localStorage.setItem('finsight.returning.v1','true')")
        rp.goto(f"{BASE}/#/login"); rp.wait_for_selector("text=Welcome back"); rc.close()
        check("returning visitor sees welcome back", True)
        pg.goto(f"{BASE}/#/upload"); pg.wait_for_selector("#view")
        if pg.locator("[data-action=reset-upload]").count(): pg.click("[data-action=reset-upload]")
        pg.wait_for_selector("[data-dropzone]"); pg.screenshot(path=f"{SHOTS}/upload-empty.png", full_page=True)
        pg.goto(f"{BASE}/#/dashboard")
        if pg.locator("text=Try the demo business").count(): pg.click("text=Try the demo business")
        pg.wait_for_selector(".kpi")
        check("demo loads dashboard with 6 KPIs", pg.locator(".kpi").count() == 6)
        check("cash on hand is real number", "27,339" in pg.locator(".kpi").first.inner_text())
        check("shortfall badge shown", pg.locator("text=Shortfall in week").count() >= 1)
        pg.goto(f"{BASE}/#/home"); pg.wait_for_selector(".hm-hero")
        check("home preview shows the loaded data's real numbers", "27,339" in pg.locator(".hm-kpis").inner_text() and "Demo business" in pg.locator(".hm-caption").inner_text() and "week" in pg.locator(".hm-insight").inner_text())
        pg.screenshot(path=f"{SHOTS}/home-demo.png", full_page=True)
        pg.goto(f"{BASE}/#/dashboard"); pg.wait_for_selector(".kpi")
